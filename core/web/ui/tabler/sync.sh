#!/usr/bin/env bash
# Regenerates data.ts from icons.txt using the Tabler Icons npm package (MIT).
# Usage: bash core/web/ui/tabler/sync.sh [version]   (needs curl + tar, no bun/python)
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
ver="${1:-latest}"
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
url="$(curl -sL "https://registry.npmjs.org/@tabler/icons/$ver" | grep -o '"tarball":"[^"]*"' | cut -d'"' -f4)"
curl -sL -o "$tmp/t.tgz" "$url"
tar xzf "$tmp/t.tgz" -C "$tmp" package/icons package/package.json package/LICENSE
version="$(grep -m1 '"version"' "$tmp/package/package.json" | cut -d'"' -f4)"
out="$here/data.ts"
{
echo "// GENERATED by sync.sh from icons.txt. Do not edit by hand."
echo "// Tabler Icons $version, MIT License, Copyright (c) 2020-2026 Paweł Kuna (https://tabler.io/icons)."
echo "// Permission is granted, free of charge, to use, copy, modify and distribute these icons subject to the MIT licence text"
echo "// shipped with @tabler/icons. 24px grid, 2px strokes (outline) or solid fills (filled). Several paths per icon are separated by |."
echo "export const outline = {"
grep -vE '^\s*(#|$)' "$here/icons.txt" | grep -v '^filled:' | while read -r n; do
  f="$tmp/package/icons/outline/$n.svg"; [ -f "$f" ] || { echo "missing outline icon: $n" >&2; exit 1; }
  d="$(grep -v 'stroke="none"' "$f" | grep -o ' d="[^"]*"' | sed 's/^ d="//; s/"$//' | tr '\n' '|' | sed 's/|$//')"
  echo "	'$n': '$d',"
done
echo "} as const"
echo "export const filled = {"
grep -E '^filled:' "$here/icons.txt" | sed 's/^filled://' | while read -r n; do
  f="$tmp/package/icons/filled/$n.svg"; [ -f "$f" ] || { echo "missing filled icon: $n" >&2; exit 1; }
  d="$(grep -v 'stroke="none"' "$f" | grep -o ' d="[^"]*"' | sed 's/^ d="//; s/"$//' | tr '\n' '|' | sed 's/|$//')"
  echo "	'$n': '$d',"
done
echo "} as const"
} > "$out"
echo "wrote $out (Tabler $version)"
